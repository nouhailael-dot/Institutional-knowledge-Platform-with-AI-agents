"""Generate the 540-580 expected-state check embedded in the SQL scripts.

The expected state is read from a local isolated database on which 540 -> 580
were applied from their committed files (never from Supabase), and written
between the markers below in every script of this folder. The same block then
runs read-only on Supabase (preflight, verify) and as the reconciliation's
precondition, so all three check exactly the same objects.

Usage (local isolated database only):
    python generate_expected_state.py ghus_v2_supabase_expected_test
"""
import sys
from pathlib import Path

import psycopg

HERE = Path(__file__).resolve().parent
BEGIN = "-- >>> expected state of 540-580 (generated by evidence/generate_expected_state.py; do not edit)"
END = "-- <<< expected state of 540-580"

# Every object 540-580 own: all of the two 540 tables, plus the two
# constraints 550 and 560 replace on older tables. Signatures are md5 of the
# catalog's own rendering, so any change in type, default, nullability,
# definition, validation, trigger state, body or comment text shows as drift.
# Function bodies are compared with CR bytes removed: on Supabase the 540 body
# was stored from a CRLF checkout and is otherwise identical.
ACTUAL = """
    actual(kind, name, sig) AS (
        SELECT 'column', c.relname || '.' || a.attname,
               md5(format_type(a.atttypid, a.atttypmod) || ' notnull=' || a.attnotnull::text
                   || ' default=' || coalesce(pg_get_expr(d.adbin, d.adrelid), ''))
        FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE n.nspname = 'public' AND c.relname IN (SELECT tbl FROM scope_tables)
          AND a.attnum > 0 AND NOT a.attisdropped
        UNION ALL
        SELECT 'constraint', cl.relname || '.' || co.conname,
               md5(co.contype::text || ' ' || pg_get_constraintdef(co.oid)
                   || ' validated=' || co.convalidated::text)
        FROM pg_constraint co JOIN pg_class cl ON cl.oid = co.conrelid
        JOIN pg_namespace n ON n.oid = cl.relnamespace
        WHERE n.nspname = 'public'
          AND (cl.relname IN (SELECT tbl FROM scope_tables)
               OR (cl.relname, co.conname) IN (SELECT tbl, con FROM scope_constraints))
        UNION ALL
        SELECT 'index', i.indexname, md5(i.indexdef)
        FROM pg_indexes i
        WHERE i.schemaname = 'public' AND i.tablename IN (SELECT tbl FROM scope_tables)
        UNION ALL
        SELECT 'trigger', c.relname || '.' || t.tgname,
               md5(pg_get_triggerdef(t.oid) || ' enabled=' || t.tgenabled::text)
        FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND NOT t.tgisinternal
          AND c.relname IN (SELECT tbl FROM scope_tables)
        UNION ALL
        SELECT 'function', p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
               md5(l.lanname || ' returns ' || format_type(p.prorettype, NULL) || ' '
                   || replace(p.prosrc, E'\\r', ''))
        FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
        JOIN pg_language l ON l.oid = p.prolang
        WHERE n.nspname = 'public' AND p.proname = 'ghus_guard_subscription_run_append_only'
        UNION ALL
        SELECT 'comment', 'column ' || c.relname || '.' || a.attname, md5(d.description)
        FROM pg_description d JOIN pg_class c ON c.oid = d.objoid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum = d.objsubid
        WHERE d.classoid = 'pg_class'::regclass AND d.objsubid > 0
          AND n.nspname = 'public' AND c.relname IN (SELECT tbl FROM scope_tables)
        UNION ALL
        SELECT 'comment', 'table ' || c.relname, md5(d.description)
        FROM pg_description d JOIN pg_class c ON c.oid = d.objoid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE d.classoid = 'pg_class'::regclass AND d.objsubid = 0
          AND n.nspname = 'public' AND c.relname IN (SELECT tbl FROM scope_tables)
        UNION ALL
        SELECT 'comment', 'constraint ' || cl.relname || '.' || co.conname, md5(d.description)
        FROM pg_description d JOIN pg_constraint co ON co.oid = d.objoid
        JOIN pg_class cl ON cl.oid = co.conrelid JOIN pg_namespace n ON n.oid = cl.relnamespace
        WHERE d.classoid = 'pg_constraint'::regclass AND n.nspname = 'public'
          AND (cl.relname IN (SELECT tbl FROM scope_tables)
               OR (cl.relname, co.conname) IN (SELECT tbl, con FROM scope_constraints))
    )"""

HEAD = """    scope_tables(tbl) AS (VALUES ('actor_update_subscription'), ('actor_update_subscription_run')),
    scope_constraints(tbl, con) AS (VALUES ('collection_run', 'ck_collection_run_cadence'),
                                       ('actor_verification_event', 'ck_actor_verification_event_origin')),"""

TAIL = """,
    drift(kind, name, problem) AS (
        SELECT coalesce(w.kind, a.kind), coalesce(w.name, a.name),
               CASE WHEN a.sig IS NULL THEN 'missing'
                    WHEN w.sig IS NULL THEN 'unexpected'
                    ELSE 'different' END
        FROM want w FULL JOIN actual a ON a.kind = w.kind AND a.name = w.name
        WHERE w.sig IS DISTINCT FROM a.sig
    )"""


def build(db: str) -> str:
    assert db.startswith("ghus_v2_") and db.endswith("_test"), "local isolated databases only"
    with psycopg.connect(host="127.0.0.1", port=55432, user="ghus_test", dbname=db) as c:
        c.execute("SET search_path = pg_catalog, public")
        rows = c.execute(f"WITH {HEAD}{ACTUAL} SELECT kind, name, sig FROM actual ORDER BY 1, 2").fetchall()
    values = ",\n".join(f"        ('{k}', '{n}', '{s}')" for k, n, s in rows)
    counts = {}
    for k, _, _ in rows:
        counts[k] = counts.get(k, 0) + 1
    summary = ", ".join(f"{v} {k}s" for k, v in sorted(counts.items()))
    return (f"{BEGIN}\n-- {len(rows)} objects: {summary}\n{HEAD}\n"
            f"    want(kind, name, sig) AS (VALUES\n{values}\n    ),{ACTUAL}{TAIL}\n{END}")


def inject(block: str) -> None:
    for path in sorted(HERE.parent.glob("*.sql")):
        text = path.read_text(encoding="utf-8")
        if BEGIN not in text:
            continue
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        path.write_bytes((head + block + tail).encode("utf-8"))
        print("updated", path.name)


if __name__ == "__main__":
    inject(build(sys.argv[1]))
