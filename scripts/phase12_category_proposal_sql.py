"""Generate migration 484 from the reviewed Phase 12 category proposal CSV.

The SQL is a pure function of `docs/evidence/phase12_category_proposals.csv`;
its header records the CSV SHA-256 so the applied migration can be traced to
the exact proposal file GHUS reviewed.
"""

from __future__ import annotations

import csv
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSV_PATH = ROOT / "docs/evidence/phase12_category_proposals.csv"
SQL_PATH = ROOT / "migrations/proposed/deferred/484_v2_phase12_category_proposals.sql"
BATCH = "phase12_existing_canonical_2026_10"


def _literal(value: str | None) -> str:
    if value is None or value == "":
        return "NULL"
    return "'" + value.replace("'", "''") + "'"


def render(csv_bytes: bytes) -> str:
    rows = list(csv.DictReader(csv_bytes.decode("utf-8").splitlines()))
    values = ",\n    ".join(
        "(" + ",".join([
            _literal(row["actor_id"]) + "::uuid",
            _literal(row["proposed_category"]),
            _literal(row["proposed_category_type"]),
            _literal(row["confidence"]),
            _literal(row["evidence"]),
            _literal(row["category_note"]),
            "true" if row["is_true_aggregate"] == "True" else "false",
        ]) + ")"
        for row in sorted(rows, key=lambda item: item["actor_id"])
    )
    digest = hashlib.sha256(csv_bytes).hexdigest()
    return f"""-- PROPOSAL ONLY. GENERATED by scripts/phase12_category_proposal_sql.py; do not edit.
-- Source: docs/evidence/phase12_category_proposals.csv sha256 {digest}
-- Applies the Phase 12 model proposals for the {len(rows)} unmappable legacy categories.
--   * real organizations: actor_category gets the proposed value (gap-fill only) and
--     stays category_needs_review=true; GHUS confirms or changes it in Review;
--   * true aggregates: no category is set; the review payload carries the
--     disposition options for GHUS. 495 cannot validate until GHUS decides them.
-- category_type is never set here (later type-only enrichment path).
BEGIN;

CREATE TEMP TABLE phase12_category_proposal(
    actor_id uuid PRIMARY KEY,
    proposed_category text,
    proposed_category_type text,
    confidence text,
    evidence text,
    category_note text,
    is_true_aggregate boolean NOT NULL
) ON COMMIT DROP;

INSERT INTO phase12_category_proposal VALUES
    {values};

DO $check$ BEGIN
  IF EXISTS (
    SELECT 1 FROM phase12_category_proposal p
    WHERE p.proposed_category IS NOT NULL
      AND NOT EXISTS (SELECT 1 FROM actor_category_definition d
                      WHERE d.category_code=p.proposed_category)
  ) THEN
    RAISE EXCEPTION '484 proposal names an unknown actor category';
  END IF;
  IF EXISTS (
    SELECT 1 FROM phase12_category_proposal p
    LEFT JOIN actor_category_migration_audit a
      ON a.actor_id=p.actor_id AND a.migration_batch_id='{BATCH}'
    WHERE a.mapping_status IS DISTINCT FROM 'requires_review'
  ) THEN
    RAISE EXCEPTION '484 proposals must target only actors awaiting category review';
  END IF;
END $check$;

UPDATE actor a
SET actor_category = p.proposed_category,
    category_needs_review = true,
    category_note = 'Phase 12 model proposal (' || p.confidence || ' confidence), pending GHUS '
                    || 'confirmation: ' || p.evidence
FROM phase12_category_proposal p
WHERE a.actor_id = p.actor_id
  AND NOT p.is_true_aggregate
  AND p.proposed_category IS NOT NULL
  AND a.actor_category IS NULL;

UPDATE review_item r
SET payload = r.payload || CASE WHEN p.is_true_aggregate THEN jsonb_build_object(
      'is_true_aggregate', true,
      'aggregate_evidence', p.evidence,
      'disposition_options', jsonb_build_array(
        'convert_to_network_parent', 'keep_as_legacy_collection_excluded_from_actor_views'),
      'disposition_decided_by', 'ghus')
    ELSE jsonb_build_object(
      'is_true_aggregate', false,
      'proposed_category', p.proposed_category,
      'proposed_category_type', p.proposed_category_type,
      'proposal_confidence', p.confidence,
      'proposal_evidence', p.evidence,
      'proposal_note', p.category_note,
      'proposal_source', 'phase12_category_proposals.csv')
    END
FROM phase12_category_proposal p
WHERE r.review_kind = 'category_doubt' AND r.entity_type = 'actor'
  AND r.entity_id = p.actor_id
  AND r.payload->>'migration_batch_id' = '{BATCH}'
  AND NOT (r.payload ? 'is_true_aggregate');

COMMIT;
"""


def main() -> int:
    SQL_PATH.write_text(render(CSV_PATH.read_bytes()), encoding="utf-8", newline="\n")
    print(f"wrote {SQL_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
